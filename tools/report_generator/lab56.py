def make_figs(T, outdir):
    D = T["lab56"]
    f = {}
    f["ctx"] = dg.idef0(D["ctx"], os.path.join(outdir, "idef0_A-0.png"))
    f["a0"] = dg.idef0(D["a0"], os.path.join(outdir, "idef0_A0.png"))
    for k, d3 in enumerate(D["idef3"]):
        f[f"i3_{k}"] = dg.idef3(d3["spec"], os.path.join(outdir, f"idef3_{k}.png"))
    return f


def _icom_rows(spec):
    rows = []
    names = {b["id"]: b["name"] for b in spec["blocks"]}
    kind = {"I": "Вход", "C": "Управление", "M": "Механизм", "O": "Выход"}
    for e in spec["ext"]:
        rows.append([e["label"].replace("\n", " "), kind[e["side"]],
                     ("Граница диаграммы → " + names[e["to"]]) if e["side"] != "O" else (names[e["to"]] + " → граница диаграммы")])
    for l in spec.get("links", []):
        rows.append([l["label"].replace("\n", " "), "Выход → " + ("вход" if l["side"] == "I" else "управление"),
                     names[l["from"]] + " → " + names[l["to"]]])
    return rows


