    b += [("pk", f"Состав пакетов приведён в таблице {t}."),
          ("table", t, "Пакеты системы", ["Пакет", "Содержимое", "Зависит от"], D["pkg_rows"], [4.2, 8.0, 4.3])]

    # ------------------------------------------------------------- 4.5 состояния
    b += [("h2", "4.5 Диаграммы состояний"), ("p", D["states_text"])]
    for k, st in enumerate(D["states"]):
        b += [("h2", f"4.5.{k + 1} {st['title']}")]
        f, n = c.fig(figs[f"state{k}"], st["caption"], st.get("w", 16.0), 20.0)
        b += [("p", st["text"].replace("{n}", n)), f]
        if st.get("rows"):
            t = c.tnum()
            b += [("pk", f"Состояния и переходы описаны в таблице {t}."),
                  ("table", t, f"Состояния объекта «{st['object']}»", ["Состояние", "Описание", "Переходы"],
                   st["rows"], [3.8, 7.0, 5.7])]

    # ------------------------------------------------------------- 4.6 компоненты
    b += [("h2", "4.6 Диаграмма компонентов")]
    f, n = c.fig(figs["components"], "Диаграмма компонентов", 16.5)
    b += [("p", D["components_text"].replace("{n}", n)), f]
    t = c.tnum()
    b += [("pk", f"Компоненты системы описаны в таблице {t}."),
          ("table", t, "Компоненты системы", ["Компонент", "Назначение", "Технология"], D["components_rows"],
           [4.2, 8.0, 4.3])]

    # ------------------------------------------------------------- 4.7 размещение
    b += [("h2", "4.7 Диаграммы размещения"), ("p", D["deploy_intro"])]
    for k, dp in enumerate(D["deploys"]):
        f, n = c.fig(figs[f"deploy{k}"], dp["caption"], dp.get("w", 16.5))
        b += [("p", dp["text"].replace("{n}", n)), f]
    t = c.tnum()
    b += [("pk", f"Узлы и размещённые на них компоненты описаны в таблице {t}."),
          ("table", t, "Узлы и компоненты системы", ["Узел", "Компоненты", "Назначение"], D["nodes"], [4.0, 5.5, 7.0])]

    # ------------------------------------------------------------- 4.8 трассировка
    b += [("h2", "4.8 Трассировка вариантов использования на классы")]
    t = c.tnum()
    rows = []
    for uc in ucs:
        p = _participants(uc["seq"])
        rows.append([uc["name"], ", ".join(p["boundary"]) or "—", ", ".join(p["control"]) or "—",
                     ", ".join(p["entity"]) or "—"])
    b += [("pk", f"Матрица трассировки (таблица {t}) показывает, какие классы участвуют в реализации каждого "
                 f"варианта использования; она построена по диаграммам последовательности раздела 4.2 и "
                 f"подтверждает, что каждый вариант использования реализуется классами общей модели."),
          ("table", t, "Трассировка вариантов использования на классы",
           ["Вариант использования", "Граничные классы", "Управляющие классы", "Классы-сущности"], rows,
           [4.0, 3.6, 4.2, 4.7])]

    b += [("h1", "5 Заключение")]
    b += [("p", x) for x in D["conclusion"]]
    b += [("h1", "6 Список используемой литературы"), ("src", T["literature"] + [
        "Буч Г., Рамбо Дж., Якобсон И. Язык UML. Руководство пользователя. — 2-е изд. — М.: ДМК Пресс, 2007. — 496 с.",
        "Леоненков А. В. Самоучитель UML 2. — СПб.: БХВ-Петербург, 2007. — 576 с.",
        "Крачтен Ф. Введение в Rational Unified Process. — 2-е изд. — М.: Вильямс, 2002. — 240 с.",
        "Unified Modeling Language Specification. Version 2.5.1. — Object Management Group, 2017. — URL: https://www.omg.org/spec/UML/2.5.1",
    ])]
    return b
