class _Ctx:
    def __init__(self):
        self.f = 0
        self.t = 1

    def fig(self, path, caption, w=16.0, max_h=None):
        self.f += 1
        b = ("fig", path, f"Рисунок 7.{self.f} – {caption}", w)
