def make_figs(T, outdir):
    D = T["lab78"]
    f = {}
    for key, src in D["puml"].items():
        f[key] = dg.plantuml(src, os.path.join(outdir, f"uml_{key}.png"))
    for k, uc in enumerate(D["usecases"]):
        f[f"seq{k}"] = dg.plantuml(uc["seq"], os.path.join(outdir, f"uml_seq_{k}.png"))
        if uc.get("vopc"):
            f[f"vopc{k}"] = dg.plantuml(uc["vopc"], os.path.join(outdir, f"uml_vopc_{k}.png"))
    return f


