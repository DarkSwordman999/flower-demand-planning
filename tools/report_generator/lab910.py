def make_figs(T, outdir):
    D = T["lab910"]
    sched, total = dg.schedule(D["stages"], START)
    assert sched[-1]["end"] <= END, (sched[-1]["end"], END)
    f = {
        "net": dg.network(sched, os.path.join(outdir, "pm_network.png"), START),
        "gantt": dg.gantt(sched, os.path.join(outdir, "pm_gantt.png"), START),
        "people": dg.gantt([dict(s, who=[PEOPLE[w] .split(" (")[0] + f" ({w})" for w in s["who"]]) for s in sched],
                           os.path.join(outdir, "pm_people.png"), START, by_person=True),
    }
    f["sched"] = sched
    f["total"] = total
    return f


